/**
 * Subsets the variable fonts used by the themes and emits src/fonts.gen.js,
 * a plain JS module of base64 data URLs.
 *
 * Keeping fonts inline is what lets the output stay a single zero-network
 * file while still having a typographic voice. system-ui is the loudest
 * "nobody designed this" signal there is.
 */
import { execFileSync } from "child_process";
import fs from "fs";
import path from "path";

const UNICODES = [
  "U+0020-007E", // basic latin
  "U+00A0",
  "U+00D7", // ×
  "U+2010-2015", // dashes
  "U+2018-201D", // smart quotes
  "U+2022", // bullet
  "U+2026", // ellipsis
  "U+2190",
  "U+2192", // arrows
  "U+00B7",
  "U+2713",
].join(",");

const FONTS = {
  archivo: "@fontsource-variable/archivo/files/archivo-latin-wght-normal.woff2",
  instrument: "@fontsource-variable/instrument-sans/files/instrument-sans-latin-wght-normal.woff2",
  newsreader: "@fontsource-variable/newsreader/files/newsreader-latin-wght-normal.woff2",
  inter: "@fontsource-variable/inter/files/inter-latin-wght-normal.woff2",
  mono: "@fontsource-variable/jetbrains-mono/files/jetbrains-mono-latin-wght-normal.woff2",
};

const out = {};
let total = 0;
for (const [name, rel] of Object.entries(FONTS)) {
  const src = path.resolve("node_modules", rel);
  if (!fs.existsSync(src)) {
    console.log(`  skip ${name} (not installed)`);
    continue;
  }
  const dst = `/tmp/sub-${name}.woff2`;
  execFileSync("pyftsubset", [
    src,
    `--unicodes=${UNICODES}`,
    "--flavor=woff2",
    "--layout-features=kern,liga,calt,tnum",
    `--output-file=${dst}`,
  ]);
  const b64 = fs.readFileSync(dst).toString("base64");
  out[name] = b64;
  const kb = (b64.length * 0.75) / 1024;
  total += kb;
  console.log(`  ${name.padEnd(12)} ${fs.statSync(src).size / 1024 | 0}KB → ${kb.toFixed(1)}KB`);
}

// Named exports, one per family, so a build that uses two typefaces
// tree-shakes the other three out instead of carrying 90KB of dead base64.
const body =
  "// GENERATED by scripts/fonts.mjs — do not edit\n" +
  Object.entries(out)
    .map(([k, v]) => `export const ${k} = "data:font/woff2;base64,${v}";`)
    .join("\n") +
  "\n";
fs.writeFileSync("src/fonts.gen.js", body);
console.log(`  total inline ${total.toFixed(1)}KB → src/fonts.gen.js`);
